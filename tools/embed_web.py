"""PlatformIO pre-build script: embeds web/ into the body firmware.

Writes src/body/WebAssets.h with every file under web/ that the page needs
(index.html and emoji/*.svg), gzipped, as byte arrays the web server sends
as they are. Embedding means an OTA update carries the page with it, and
there's no separate filesystem upload to forget.

Runs on every build of body_s3; the header is only rewritten when it changes.
"""
import gzip
from pathlib import Path

try:
    Import("env")  # noqa: F821  (PlatformIO)
    ROOT = Path(env["PROJECT_DIR"])  # noqa: F821
except NameError:  # run by hand
    ROOT = Path(__file__).resolve().parent.parent

WEB = ROOT / "web"
OUT = ROOT / "src/body/WebAssets.h"
TYPES = {".html": "text/html; charset=utf-8", ".svg": "image/svg+xml", ".png": "image/png"}


def assets():
    files = [WEB / "index.html"] + sorted((WEB / "emoji").glob("*.svg"))
    return [f for f in files if f.is_file()]


def build():
    parts = ["// Generated by tools/embed_web.py from web/. Do not edit; rebuild instead.",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "", "namespace web {", "",
             "struct Asset {", "  const char* path;", "  const char* type;", "  const uint8_t* data;",
             "  size_t size;", "};", ""]
    table = []
    for i, f in enumerate(assets()):
        data = gzip.compress(f.read_bytes(), compresslevel=9, mtime=0)
        name = f"kAsset{i}"
        rows = [", ".join(f"0x{b:02x}" for b in data[j:j + 20]) for j in range(0, len(data), 20)]
        parts.append(f"// {f.relative_to(WEB)}: {f.stat().st_size} bytes, {len(data)} gzipped")
        parts.append(f"const uint8_t {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};")
        path = "/" if f.name == "index.html" else "/" + str(f.relative_to(WEB)).replace("\\", "/")
        table.append(f'  {{"{path}", "{TYPES.get(f.suffix, "application/octet-stream")}", {name}, sizeof({name})}},')
    parts += ["", "const Asset kAssets[] = {"] + table + ["};",
              "const size_t kAssetCount = sizeof(kAssets) / sizeof(kAssets[0]);", "", "}  // namespace web", ""]
    text = "\n".join(parts)
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)
        print("embed_web: wrote", OUT.relative_to(ROOT), "with", len(table), "files")


build()
