#!/usr/bin/env python3
"""Turns the dome Maestro's settings file into lib/DroidCore/src/ServoSequenceData.cpp.

Each Maestro position (quarter-microseconds) becomes thousandths of the way
from that panel's Closed to Open, using the Maestro's own endpoints: Closed is
the channel's home, Open is its position in the "All Open" sequence.

    python3 tools/gen_servo_sequences.py
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools/maestro/dome-maestro-settings.txt"
OUT = ROOT / "lib/DroidCore/src/ServoSequenceData.cpp"
CHANNELS = [0, 1, 2, 3, 7, 8, 9, 10, 11, 12, 13]  # Pie 1-4, Dome panels 1-7

text = SRC.read_text()
root = ET.fromstring(text[text.index("<UscSettings"):])
chans = root.find("Channels").findall("Channel")
seqs = root.find("Sequences")
all_open = [int(x) for x in [s for s in seqs if s.get("name") == "All Open"][0].find("Frame").text.split()[:18]]
closed = {c: int(chans[c].get("home")) for c in CHANNELS}
opened = {c: all_open[c] for c in CHANNELS}

# Script order is what restartScript(n) ran.
order = re.findall(r"^# (.+)\nsub ", root.find("Script").text, re.M)

lines = ['// Generated by tools/gen_servo_sequences.py from tools/maestro/dome-maestro-settings.txt.',
         '// Do not edit by hand; edit the generator or the settings file and run it again.',
         '#include "ServoSequences.h"', '', 'namespace droid {', '', 'namespace {', '']
entries = []
for i, name in enumerate(order):
    seq = [s for s in seqs if s.get("name") == name][0]
    ident = f"kSeq{i}"
    lines.append(f"// {name}")
    lines.append(f"const ServoFrame {ident}[] = {{")
    for f in seq.findall("Frame"):
        q = [int(x) for x in f.text.split()[:18]]
        pos = []
        for c in CHANNELS:
            v = q[c]
            if v == 0:
                pos.append("kHoldPosition")
            else:
                pos.append(str(round((v - closed[c]) * 1000 / (opened[c] - closed[c]))))
        lines.append(f"    {{{f.get('duration')}, {{{', '.join(pos)}}}}},")
    lines.append("};")
    lines.append("")
    entries.append(f'    {{"{name}", {ident}, sizeof({ident}) / sizeof({ident}[0])}},')

lines += ["}  // namespace", "", "const ServoSequence kServoSequences[] = {"] + entries + [
    "};", "const size_t kServoSequenceCount = sizeof(kServoSequences) / sizeof(kServoSequences[0]);",
    "", "}  // namespace droid", ""]
OUT.write_text("\n".join(lines))
print("wrote", OUT, "with", len(order), "sequences")
